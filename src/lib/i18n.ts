export function translate(key: string, lang: string): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dictionary[key] || TRANSLATIONS.en[key] || key;
}

export function formatCurrency(amount: number, countryCode: string): string {
  const config = COUNTRIES[countryCode] || COUNTRIES.US;
  return `${config.currencySymbol}${amount.toLocaleString(undefined, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  })}`;
}

export function formatDate(dateStr: string, countryCode: string): string {
  if (!dateStr) return "";
  const parts = dateStr.split("-"); // Expecting YYYY-MM-DD
  if (parts.length !== 3) return dateStr;
  const [year, month, day] = parts;
  const config = COUNTRIES[countryCode] || COUNTRIES.US;

  if (config.dateFormat === "DD/MM/YYYY") return `${day}/${month}/${year}`;
  if (config.dateFormat === "DD-MM-YYYY") return `${day}-${month}-${year}`;
  if (config.dateFormat === "MM/DD/YYYY") return `${month}/${day}/${year}`;
  return dateStr;
}

export function getRTL(lang: string): boolean {
  const language = LANGUAGES.find(l => l.code === lang);
  return language ? language.rtl : false;
}
